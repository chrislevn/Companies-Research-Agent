const browserIsVietnamese = (navigator.language || "").toLowerCase().startsWith("vi");
let LANG = localStorage.getItem("cr-lang") || (browserIsVietnamese ? "vi" : "en");

function t(key, vars) {
  let text = (STRINGS[LANG] && STRINGS[LANG][key]) || STRINGS.en[key] || key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, v);
  return text;
}

function setLang(lang) {
  LANG = lang;
  localStorage.setItem("cr-lang", lang);
  document.documentElement.lang = lang;
  applyTranslations();
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  const toggle = document.getElementById("lang-toggle");
  if (toggle) toggle.textContent = t("lang.other");
}
